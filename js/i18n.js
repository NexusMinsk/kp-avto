const LANGS = ['ru', 'en', 'zh'];
const LANG_ATTR = { ru: 'ru', en: 'en', zh: 'zh-CN' };

function t(key) {
  const lang = document.documentElement.dataset.lang || 'ru';
  const parts = key.split('.');
  let cur = I18N[lang] || I18N.ru;
  for (const part of parts) {
    cur = cur?.[part];
  }
  if (typeof cur === 'string') return cur;
  cur = I18N.ru;
  for (const part of parts) {
    cur = cur?.[part];
  }
  return typeof cur === 'string' ? cur : key;
}

function applyLang(lang) {
  if (!LANGS.includes(lang)) lang = 'ru';
  document.documentElement.lang = LANG_ATTR[lang];
  document.documentElement.dataset.lang = lang;
  try {
    localStorage.setItem('kp-lang', lang);
  } catch {
    /* ignore */
  }

  document.title = t('meta.title');
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute('content', t('meta.description'));

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    if (el.id === 'trackLabel') return;
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.dataset.i18nTitle));
  });
  document.querySelectorAll('[data-lang]').forEach((btn) => {
    const on = btn.dataset.lang === lang;
    btn.classList.toggle('is-on', on);
    btn.setAttribute('aria-pressed', on ? 'true' : 'false');
  });

  document.dispatchEvent(new CustomEvent('kp:lang', { detail: lang }));
}

function bindLangSwitch() {
  document.querySelectorAll('[data-lang]').forEach((btn) => {
    btn.addEventListener('click', () => applyLang(btn.dataset.lang));
  });
}

function initLang() {
  let lang = 'ru';
  try {
    lang = localStorage.getItem('kp-lang') || 'ru';
  } catch {
    lang = 'ru';
  }
  bindLangSwitch();
  applyLang(lang);
}

initLang();
